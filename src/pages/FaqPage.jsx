  const handleContact = (e) => {
    e.preventDefault();
    window.open(`mailto:${EMAIL}?subject=${encodeURIComponent('Enquiry from ' + contactForm.name)}&body=${encodeURIComponent(contactForm.message + '\n\nFrom: ' + contactForm.name + ' (' + contactForm.email + ')')}`, '_blank');
    setSent(true);
  };

