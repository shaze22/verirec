const COUNSELOR_NAV = [
  { to: '/analytics',               label: 'Dashboard',  icon: I.chart },
  { to: '/kaunselor/clients',       label: 'Klien',      icon: I.users },
  { to: '/kaunselor/appointments',  label: 'Temujanji',  icon: I.calendar },
  { to: '/settings',                label: 'Tetapan',    icon: I.settings },
];

const OTHER_NAV = [
  { to: '/analytics',   label: 'Utama',     icon: I.home },
  { to: '/session/new', label: 'Sesi',      icon: I.mic },
  { to: '/subjects',    label: 'Subjek',    icon: I.users },
  { to: '/cases',       label: 'Fail Kes',  icon: I.folder },
  { to: '/settings',    label: 'Tetapan',   icon: I.settings },
];

export function BottomNav() {
  const isCounselor = isCounselorSubdomain();
  const { signOut } = useAuthStore();
  const navigate = useNavigate();
  const navItems = isCounselor ? COUNSELOR_NAV : OTHER_NAV;

  const handleSignOut = async () => {
    await signOut();
    navigate('/logout');
  };

  return (
    <nav className="fixed bottom-0 left-0 right-0 h-16 bg-white border-t flex items-center z-50 md:hidden">
      {navItems.map(item => (
        <NavLink
          key={item.to}
          to={item.to}
          className={({ isActive }) => clsx(
            'flex-1 flex flex-col items-center justify-center gap-0.5 py-2 text-xs font-medium transition-colors',
            isActive ? 'text-blue-600' : 'text-gray-400'
          )}
        >
          {item.icon}
          {item.label}
        </NavLink>
      ))}
      {/* Logout button — mobile only, counselor subdomain only */}
      {isCounselor && (
        <button
          onClick={handleSignOut}
          className="flex-1 flex flex-col items-center justify-center gap-0.5 py-2 text-xs font-medium text-red-400 hover:text-red-600 transition-colors"
        >
          {I.logout}
          Keluar
        </button>
      )}
    </nav>
  );
}
